class Footprint(BaseModel):
    shape: Literal["circle", "rectangle"] = "circle"
    radius: float = Field(0.35, gt=0, description="circle radius (m)")
    length: float | None = Field(None, gt=0)
    width: float | None = Field(None, gt=0)

    @property
    def effective_radius(self) -> float:
        if self.shape == "rectangle" and self.length and self.width:
            return 0.5 * (self.length**2 + self.width**2) ** 0.5
        return self.radius

    @property
    def effective_width(self) -> float:
        if self.shape == "rectangle" and self.width:
            return self.width
        return 2 * self.radius


