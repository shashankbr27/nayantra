"""
nayantra/core/models.py

Schemas for everything the Nayantra Core owns: maps, waypoints (= nav-graph
vertices), lanes, zones, fleets, robots, live robot state, tasks, traffic and
events. These are the single source of truth for the REST API, the WebSocket
stream, the MCP tools and persistence.

All ids are short slugs so they read well in logs and explanations
("UGV-03 is waiting for lane L12 held by UGV-01").
"""

