class FleetBase(Schema):
    name: str = Field(..., min_length=1, max_length=120)
    robot_type: RobotType
    description: str = ""
    color: str = Field("#38bdf8", pattern=r"^#[0-9a-fA-F]{6}$")
    capabilities: list[str] = Field(default_factory=lambda: ["navigate"])
    navigation: FleetNavigation = Field(default_factory=FleetNavigation)
    footprint: Footprint = Field(default_factory=Footprint)
    limits: MotionLimits = Field(default_factory=MotionLimits)
    battery: BatteryPolicy = Field(default_factory=BatteryPolicy)
    charging_required: bool = True
    map_ids: list[str] = Field(default_factory=list, description="maps this fleet may operate on")
    layer: Layer = Layer.GROUND
    communication: CommunicationConfig = Field(default_factory=CommunicationConfig)
    priority: int = Field(5, ge=0, le=9, description="default traffic priority")
    config: dict[str, Any] = Field(default_factory=dict)

    @field_validator("capabilities")
    @classmethod
    def _caps(cls, v: list[str]) -> list[str]:
        out = []
        for cap in v:
            cap = slugify(cap)
            if cap not in out:
                out.append(cap)
        return out


